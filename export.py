"""Export approved stories to CSV and Markdown (PRD US-08, US-10).

Only stories that are approved AND still pass every blocking quality check are
exported (US-08 AC-04). The PRD summary, raw notes, dropped stories and
unapproved stories are never exported (US-08 export boundary).
Jira export (US-14, Could) is not in this release (DEC-31).
"""

from __future__ import annotations

import csv
import io

from quality import can_approve
from schemas import Backlog, Story
from scoring import rice_for_story


class NoApprovedStoriesError(ValueError):
    pass


def exportable_stories(backlog: Backlog, notes: str | None = None) -> list[Story]:
    return [s for s in backlog.stories if s.approved and can_approve(s, notes)]


def _require(stories: list[Story]) -> None:
    if not stories:
        raise NoApprovedStoriesError("No approved stories to export. Approve at least one story first.")


def test_cases(story: Story) -> list[dict]:
    """US-10: one functional test case per acceptance criterion, derived by
    code from the Gherkin (not generated by the AI), so it cannot drift."""
    return [
        {
            "id": f"TC-{story.id}-{i}",
            "story_id": story.id,
            "criterion": f"AC-{i}",
            "precondition": ac.given,
            "step": ac.when,
            "expected": ac.then,
        }
        for i, ac in enumerate(story.acceptance_criteria, start=1)
    ]


def _criteria_text(story: Story) -> str:
    return "\n".join(
        f"AC-{i}: Given {ac.given}; When {ac.when}; Then {ac.then}"
        for i, ac in enumerate(story.acceptance_criteria, start=1)
    )


CSV_COLUMNS = [
    "ID", "Epic", "Title", "User story", "Acceptance criteria", "MoSCoW",
    "Story points", "RICE", "Depends on", "Evidence quote", "Approved",
]


def to_csv(backlog: Backlog, notes: str | None = None) -> bytes:
    stories = exportable_stories(backlog, notes)
    _require(stories)
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(CSV_COLUMNS)
    for s in stories:
        writer.writerow([
            s.id, s.epic_id, s.title, s.sentence(), _criteria_text(s), s.moscow,
            s.points, rice_for_story(s).label(), ", ".join(s.depends_on),
            s.evidence_quote, "true",
        ])
    return buffer.getvalue().encode("utf-8")


def to_markdown(backlog: Backlog, notes: str | None = None, title: str = "Approved backlog") -> bytes:
    stories = exportable_stories(backlog, notes)
    _require(stories)
    epics = {e.id: e.title for e in backlog.epics}
    lines = [f"# {title}", "", f"{len(stories)} approved user stories.", ""]
    for s in stories:
        lines += [
            f"## {s.id} — {s.title}",
            "",
            f"**Epic:** {s.epic_id} — {epics.get(s.epic_id, '')}  ",
            f"**Priority:** {s.moscow} · **Points:** {s.points} · **RICE:** {rice_for_story(s).label()}  ",
            f"**Depends on:** {', '.join(s.depends_on) or 'None'}",
            "",
            s.sentence(),
            "",
            "**Acceptance criteria**",
            "",
        ]
        for i, ac in enumerate(s.acceptance_criteria, start=1):
            lines += [f"- **AC-{i}** Given {ac.given}, when {ac.when}, then {ac.then}."]
        lines += ["", f"> Evidence: \"{s.evidence_quote}\"", "", "**Test cases**", ""]
        lines += ["| ID | Precondition | Step | Expected result |", "| --- | --- | --- | --- |"]
        for tc in test_cases(s):
            lines.append(f"| {tc['id']} | {tc['precondition']} | {tc['step']} | {tc['expected']} |")
        lines.append("")
    return "\n".join(lines).encode("utf-8")
